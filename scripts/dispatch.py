#!/usr/bin/env python3
"""Dispatch one registered target as a supervised job with scope enforcement and a result envelope.

Blocking (short tasks, tests):
  dispatch.py <target> <label> <mode> <prompt-file> <artifact-root> <product-root>
Detached (long tasks; the orchestrator polls):
  dispatch.py start  <target> <label> <mode> <prompt-file> <artifact-root> <product-root>   -> prints {"job_id": ...}
  dispatch.py status <job-id>                      current state, progress, usage, resume time
  dispatch.py wait   <job-id> [--seconds N]        block up to N seconds (default 300) for a terminal state
  dispatch.py cancel <job-id>
  dispatch.py list
Other:
  dispatch.py health <target>
  dispatch.py usage  <target> [--refresh]          subscription usage windows and the suspend decision

There is no turn limit. A run stops only when it stalls (no output for idle_timeout_seconds), passes the wall-clock backstop
(max_wall_seconds, 0 disables), is cancelled, or crosses the usage guard. When a guarded usage window (five hour) drops below the
configured headroom, the job is suspended and its own session is resumed after the window resets. A blocking window (weekly)
stops the job for a human decision. Thresholds live in targets/stage-assignment-rules.toml.

The prompt file carries the scope as marker lines, generated by the controller from the recorded Execution Unit or assigned
artifact path:
  WORKFLOW_ARTIFACT_PATH=<artifact-root-relative path>      (artifact mode, exactly one)
  WORKFLOW_ALLOWED_PATH=<repo-relative path or dir/>        (zero or more; required in execution mode)
  WORKFLOW_RESULT_ARTIFACT_PATH=<artifact-root-relative>    (execution mode, at most one)
  WORKFLOW_VALIDATION_COMMAND=<exact command>               (execution mode, zero or more)

Environment:
  WORKFLOW_ROLE                     role being dispatched; targets not eligible for it are skipped
  WORKFLOW_FALLBACK_CHAIN           comma-separated recorded fallback targets, tried after an unavailable, unsuitable,
                                    usage-limited, or timed-out attempt
  WORKFLOW_STATE_DIR                job and usage state (default <shared root>/state)
  WORKFLOW_DISPATCH_TIMEOUT_SECONDS / WORKFLOW_IDLE_TIMEOUT_SECONDS / WORKFLOW_USAGE_HEADROOM   policy overrides
  CLAUDE_WORKER_MAX_TURNS           optional turn limit; unset means none
  CODEX_CLI_PATH                    Codex binary when it is not on PATH
  WORKFLOW_DISPATCH_ALLOW_MOCK=1 with WORKFLOW_DISPATCH_MOCK_COMMAND / WORKFLOW_USAGE_MOCK_FILE   test-only doubles
"""

